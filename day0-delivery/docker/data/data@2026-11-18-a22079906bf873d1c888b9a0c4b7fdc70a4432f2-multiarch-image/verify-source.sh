#!/usr/bin/env bash
# Compare a source tree against the cutoff manifest.
# Usage: verify-source.sh <tree> <manifest-dir>
set -euo pipefail

TREE=$1
MANIFEST=$(realpath "$2")
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT

cd "$TREE"

sha256sum --quiet -c "$MANIFEST/cutoff-files.sha256"

while IFS=$'\t' read -r path target; do
    [ "$(readlink "$path")" = "$target" ] || { echo "SYMLINK MISMATCH: $path"; exit 1; }
done < "$MANIFEST/cutoff-symlinks.tsv"

find . \( -name .git -o -name __pycache__ -o -path ./python/sglang.egg-info \) -prune \
    -o \( -type f -o -type l \) -printf '%P\n' | LC_ALL=C sort > "$WORK/actual"
{ sed -E 's/^[0-9a-f]{64} [ *]//' "$MANIFEST/cutoff-files.sha256"; cut -f1 "$MANIFEST/cutoff-symlinks.tsv"; } \
    | LC_ALL=C sort > "$WORK/expected"

LC_ALL=C comm -13 "$WORK/actual" "$WORK/expected" > "$WORK/missing"
LC_ALL=C comm -23 "$WORK/actual" "$WORK/expected" > "$WORK/extra"

# Generated by the editable install; ignored by the repo's .gitignore.
grep -v -E '^python/sglang/(_version\.py|srt/rust_extensions/_(bench|grpc|multimodal|server)\.cpython-[0-9]+-[a-z0-9_]+-linux-gnu\.so|srt/mem_cache/rust_tree_core/mem_cache\.cpython-[0-9]+-[a-z0-9_]+-linux-gnu\.so)$' \
    "$WORK/extra" > "$WORK/unexpected" || true

echo "tracked files matched: $(wc -l < "$MANIFEST/cutoff-files.sha256")"
echo "symlinks matched: $(wc -l < "$MANIFEST/cutoff-symlinks.tsv")"
echo "generated files outside the manifest:"
sed 's/^/  /' "$WORK/extra"

if [ -s "$WORK/missing" ] || [ -s "$WORK/unexpected" ]; then
    echo "MISSING:"; cat "$WORK/missing"
    echo "UNEXPECTED:"; cat "$WORK/unexpected"
    exit 1
fi
echo "SOURCE_MATCHES_CUTOFF"
